// Copies monaco-editor into a version-stamped assets folder and writes the matching
// version constant, so an upgrade changes the asset URL and busts stale CDN/browser caches.
// Single source of truth: the installed monaco-editor version.
import { createRequire } from 'node:module';
import { cpSync, existsSync, mkdirSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const require = createRequire(import.meta.url);
const version = require('monaco-editor/package.json').version;

const assetsDir = join(process.cwd(), 'src', 'assets');
const dest = join(assetsDir, `monaco-editor-${version}`);
const src = join(process.cwd(), 'node_modules', 'monaco-editor', 'min');

// drop stale version folders from previous installs
for (const entry of existsSync(assetsDir) ? readdirSync(assetsDir) : []) {
  if (entry.startsWith('monaco-editor-') && entry !== `monaco-editor-${version}`) {
    rmSync(join(assetsDir, entry), { recursive: true, force: true });
  }
}

if (!existsSync(join(dest, 'min', 'vs', 'loader.js'))) {
  mkdirSync(dest, { recursive: true });
  cpSync(src, join(dest, 'min'), { recursive: true });
}

writeFileSync(
  join(process.cwd(), 'src', 'app', 'monaco-version.ts'),
  `// generated by tools/copy-monaco.mjs — do not edit\nexport const MONACO_VERSION = '${version}';\n`
);

console.log(`monaco-editor ${version} ready at assets/monaco-editor-${version}`);
